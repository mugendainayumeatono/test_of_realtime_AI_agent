#!/usr/bin/env bash
# ==============================================================================
# 成田机场（RJAA / NRT）场景初始化脚本
# 
# 功能说明：
#   1. 初始化空域场景：使用 CLI 停止模拟器和管制员，清除全部飞机和机场；
#   2. 设置成田国际机场坐标（纬度 35.7686°N, 经度 140.3887°E, 跑道航向 157°）；
#   3. 在机场周边 20 海里空域边界的随机位置生成一架 4000 英尺（ft）高度的飞机；
#   4. 启动飞行物理模拟器推算循环与 AI 飞行航路管制员（Controller）。
# ==============================================================================

set -euo pipefail

# 定位脚本所在的项目根目录
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "${PROJECT_ROOT}"

# 自动选择 CLI 运行方式 (优先 uv, 其次本地虚拟环境, 最后系统 python3)
if command -v uv &>/dev/null; then
    CLI_RUNNER=(uv run python cli/cli.py)
elif [ -f ".venv/bin/python" ]; then
    CLI_RUNNER=(.venv/bin/python cli/cli.py)
else
    CLI_RUNNER=(python3 cli/cli.py)
fi

# ------------------------------------------------------------------------------
# 场景参数配置
# ------------------------------------------------------------------------------
# 成田国际机场 (Narita International Airport, RJAA / NRT)
# 经纬度基准参考点：35.7686° N, 140.3887° E
# 主跑道 16R / 34L 磁航向约 157°
AIRPORT_LAT="35.7686"
AIRPORT_LON="140.3887"
RUNWAY_HEADING="157"

# 目标生成高度：4000 英尺 (4000 ft)
ALTITUDE_FEET="4000"

# 飞机初始参数
AIRCRAFT_NAME="JA-NRT-4000"
AIRCRAFT_SPEED="220"

echo "=================================================================="
echo "         成田机场 (RJAA / NRT) 场景初始化与启动脚本"
echo "=================================================================="
echo "项目目录: ${PROJECT_ROOT}"
echo "CLI 解释器: ${CLI_RUNNER[*]}"
echo ""

# ------------------------------------------------------------------------------
# 0. 环境初始化与重置 (停止模拟器和管制员，清除全部飞机和机场)
# ------------------------------------------------------------------------------
echo ">>> [步骤 1/4] 初始化空域场景：使用 CLI 停止模拟器和管制员，清除全部飞机和机场..."
"${CLI_RUNNER[@]}" reset

echo ""

# ------------------------------------------------------------------------------
# 1. 设置机场坐标
# ------------------------------------------------------------------------------
echo ">>> [步骤 2/4] 设置成田国际机场经纬度与跑道航向..."
echo "    - 机场纬度 (Latitude):  ${AIRPORT_LAT}° N"
echo "    - 机场经度 (Longitude): ${AIRPORT_LON}° E"
echo "    - 跑道航向 (Heading):    ${RUNWAY_HEADING}°"

"${CLI_RUNNER[@]}" airport set \
    --lat "${AIRPORT_LAT}" \
    --lon "${AIRPORT_LON}" \
    --heading "${RUNWAY_HEADING}"

echo ""

# ------------------------------------------------------------------------------
# 3. 在 4000 英尺高度的随机位置生成飞机
# ------------------------------------------------------------------------------
echo ">>> [步骤 3/4] 在 4000 英尺 (4000 ft) 高度的随机位置生成飞机..."
echo "    - 飞机呼号 (Callsign):   ${AIRCRAFT_NAME}"
echo "    - 初始高度 (Altitude):   ${ALTITUDE_FEET} 英尺 (ft)"
echo "    - 初始空速 (Speed):      ${AIRCRAFT_SPEED} 节"
echo "    - 位置策略 (Position):   成田机场周边 20 NM 随机边界点"

"${CLI_RUNNER[@]}" airplane add \
    --name "${AIRCRAFT_NAME}" \
    --altitude "${ALTITUDE_FEET}" \
    --speed "${AIRCRAFT_SPEED}" \
    --random-pos

echo ""

# ------------------------------------------------------------------------------
# 4. 启动模拟器推算与 AI 管制员
# ------------------------------------------------------------------------------
echo ">>> [步骤 4/4] 启动飞行物理模拟器与 AI 飞行管制员..."

echo " -> 正在启动飞行模拟器 (Airplane Simulator)..."
"${CLI_RUNNER[@]}" simulator on

echo " -> 正在启动 AI 管制员 (Agent Controller)..."
"${CLI_RUNNER[@]}" controller on

echo ""
echo "=================================================================="
echo " 场景启动完成！当前空域实时飞行状态："
echo "=================================================================="
"${CLI_RUNNER[@]}" airplane status
echo ""
echo "提示: 可通过网页端 http://localhost:8010 观察雷达地图与无线电通信。"
